#!/usr/bin/env node
// Compiles the design system's tokens.json into a typed React Native theme.
// The design system is the single source of truth; src/theme/tokens.ts is generated.
// Run: npm run theme
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, '../../design-system/tokens.json');
const OUT = resolve(here, '../src/theme/tokens.ts');

const tokens = JSON.parse(readFileSync(SRC, 'utf8'));
const themes = tokens.color.themes.map((t) => t.id);
const [primary] = themes;

/** A token's raw value for one theme; a bare string belongs to the primary theme. */
function rawValue(token, theme) {
  const v = token.value;
  if (typeof v === 'string') return theme === primary ? v : (v ?? null);
  return v[theme] ?? v[primary] ?? null;
}

/** Resolve `{other-token}` aliases. Throws on a missing target or a cycle. */
function resolveColor(name, theme, byName, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Alias cycle at colour "${name}" (${theme})`);
  const token = byName.get(name);
  if (!token) throw new Error(`Unknown colour token "${name}" referenced in theme ${theme}`);
  const raw = rawValue(token, theme);
  if (raw === null) throw new Error(`Colour "${name}" has no value in theme ${theme}`);
  const alias = /^\{([A-Za-z0-9_.-]+)\}$/.exec(raw.trim());
  if (!alias) return raw;
  return resolveColor(alias[1], theme, byName, new Set(seen).add(name));
}

const byName = new Map(tokens.color.tokens.map((t) => [t.name, t]));
const palette = {};
for (const theme of themes) {
  palette[theme] = {};
  for (const t of tokens.color.tokens) palette[theme][t.name] = resolveColor(t.name, theme, byName);
}

/** "16px" | "0" | 16 -> 16 */
function px(value) {
  if (typeof value === 'number') return value;
  const m = /^(-?[\d.]+)(px)?$/.exec(String(value).trim());
  if (!m) throw new Error(`Cannot convert "${value}" to a React Native number`);
  return Number(m[1]);
}

const scale = (family) =>
  Object.fromEntries(tokens[family].tokens.map((t) => [t.name, px(t.value)]));

// React Native picks a font file per weight; it does not synthesise one.
const FONT_FILES = {
  display: () => 'PiePie',
  sans: (w) => ({ 400: 'JosefinSans_400Regular', 600: 'JosefinSans_600SemiBold', 700: 'JosefinSans_700Bold' })[w]
    ?? (() => { throw new Error(`No Josefin Sans file for weight ${w}; only 400, 600 and 700 are loaded`); })(),
};

const typography = {};
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    const familyKey = style.family ?? group.family;
    const pick = FONT_FILES[familyKey];
    if (!pick) throw new Error(`No React Native mapping for font family "${familyKey}"`);
    const weight = Number(style.fontWeight);
    typography[style.name] = {
      fontFamily: pick(weight),
      fontSize: px(style.fontSize),
      lineHeight: px(style.lineHeight),
      ...(style.letterSpacing ? { letterSpacing: px(style.letterSpacing) } : {}),
    };
  }
}

const j = (v) => JSON.stringify(v, null, 2);
writeFileSync(OUT, `// GENERATED by scripts/generate-theme.mjs from design-system/tokens.json.
// Do not edit by hand — change the design system and run \`npm run theme\`.

export const palette = ${j(palette)} as const;

export const spacing = ${j(scale('spacing'))} as const;

export const radius = ${j(scale('radius'))} as const;

export const typography = ${j(typography)} as const;

export type ThemeName = keyof typeof palette;
export type ColorToken = keyof (typeof palette)['${primary}'];
export type SpacingToken = keyof typeof spacing;
export type RadiusToken = keyof typeof radius;
export type TypeToken = keyof typeof typography;
`);

console.log(
  `theme: ${Object.keys(palette[primary]).length} colours x ${themes.length} themes, ` +
  `${Object.keys(scale('spacing')).length} spacing, ${Object.keys(scale('radius')).length} radii, ` +
  `${Object.keys(typography).length} type styles -> src/theme/tokens.ts`
);
